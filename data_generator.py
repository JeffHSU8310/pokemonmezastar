def calculate_defensive_profile(defender_types: List[str]):
    """計算特定屬性組合的弱點、抵抗、無效屬性"""
    weaknesses = []
    resistances = []
    immunities = []

    for atk_t in TYPES:
        mult = 1.0
        for def_t in defender_types:
            if def_t in TYPE_CHART.get(atk_t, {}):
                mult *= TYPE_CHART[atk_t][def_t]
        
        if mult >= 2.0:
            weaknesses.append(f"{atk_t} ({mult}x)")
        elif mult == 0.0:
            immunities.append(f"{atk_t} (0x)")
        elif mult <= 0.5:
            resistances.append(f"{atk_t} ({mult}x)")

    return weaknesses, resistances, immunities

